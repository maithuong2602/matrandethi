import { describe, it, expect } from 'vitest';
import { parseParts, generateExamWordHtml, generateExamVariants } from '../utils';
import { splitLegacyTrueFalseQuestions } from '../pages/QuestionManager';
import { buildDefaultFileName, detectGradeFromContext } from '../pages/ExamGenerator';
import { ExerciseQuestion } from '../types';

describe('AI Essay Rubric Table Format Tests', () => {
  it('parseParts should parse standard a), b), c) rubric generated by AI into distinct table rows', () => {
    const rawRubric = `a) Nêu được khái niệm thiết bị vào và lấy ví dụ đúng - 0,5 điểm.\nb) Nêu được khái niệm thiết bị ra và lấy ví dụ đúng - 0,5 điểm.`;
    const parts = parseParts(rawRubric);

    expect(parts.length).toBe(2);
    expect(parts[0].label).toBe('a)');
    expect(parts[0].content).toContain('khái niệm thiết bị vào');
    expect(parts[0].content).toContain('0,5 điểm');
    expect(parts[1].label).toBe('b)');
    expect(parts[1].content).toContain('khái niệm thiết bị ra');
    expect(parts[1].content).toContain('0,5 điểm');
  });

  it('generateExamWordHtml should render 2-column nested table for multi-part rubric', () => {
    const essayQ: ExerciseQuestion = {
      id: 'q_essay_1',
      category: 'essay',
      questionType: 'essay',
      level: 'TH',
      content: 'Câu 1. Nêu vai trò của phần cứng và phần mềm máy tính:\na) Phần cứng máy tính\nb) Phần mềm máy tính',
      answer: 'a) Phần cứng là các thiết bị vật lý cụ thể cấu thành máy tính - 0,5 điểm.\nb) Phần mềm là các chương trình chỉ dẫn máy tính hoạt động - 0,5 điểm.',
      points: 1.0,
      lesson: 'Bài 1: Thiết bị vào - ra'
    };

    const html = generateExamWordHtml([essayQ], {
      donVi: 'PHÒNG GD&ĐT',
      tenTruong: 'THCS LÊ HỒNG PHONG',
      tenKyThi: 'KIỂM TRA GIỮA KÌ I',
      monHoc: 'MÔN: TIN HỌC – LỚP 7'
    });

    // Check that nested table exists with 2 columns
    expect(html).toContain('<b>a)</b>');
    expect(html).toContain('Phần cứng máy tính');
    expect(html).toContain('<b>b)</b>');
    expect(html).toContain('Phần mềm máy tính');
    expect(html).toContain('0,5 điểm');
  });
});

describe('New True/False Single Independent Question Format Tests', () => {
  it('splitLegacyTrueFalseQuestions should split 4-part legacy question into 4 independent questions', () => {
    const legacyQ: ExerciseQuestion = {
      id: 'tf_legacy_1',
      category: 'mc',
      questionType: 'true-false',
      level: 'NB',
      criteria: '1.1',
      content: 'Khi sử dụng máy tính, học sinh cần chú ý các quy tắc an toàn:',
      options: [
        { id: 'a', text: 'Không chạm vào dây điện hở.', isCorrect: true },
        { id: 'b', text: 'Vừa ăn uống vừa sử dụng bàn phím.', isCorrect: false },
        { id: 'c', text: 'Tắt máy đúng quy trình khi không dùng.', isCorrect: true },
        { id: 'd', text: 'Tự ý tháo mở vỏ thùng máy khi chưa ngắt điện.', isCorrect: false }
      ],
      points: 1.0,
      lesson: 'Bài 1: Sử dụng máy tính an toàn'
    };

    const split = splitLegacyTrueFalseQuestions([legacyQ]);
    expect(split.length).toBe(4);

    expect(split[0].questionType).toBe('true-false');
    expect(split[0].content).toContain('Không chạm vào dây điện hở');
    expect(split[0].answer).toBe('Đúng');
    expect(split[0].points).toBe(0.25);

    expect(split[1].content).toContain('Vừa ăn uống vừa sử dụng bàn phím');
    expect(split[1].answer).toBe('Sai');
    expect(split[1].points).toBe(0.25);
  });

  it('generateExamWordHtml should NOT print A, B, C, D options for true-false questions in exam paper', () => {
    const tfQ: ExerciseQuestion = {
      id: 'tf_single_1',
      category: 'mc',
      questionType: 'true-false',
      level: 'NB',
      content: 'Khi máy tính đang xử lí dữ liệu, việc ngắt nguồn điện đột ngột có thể gây lỗi tệp tin hệ thống.',
      options: [
        { id: 'Đúng', text: 'Đúng', isCorrect: true },
        { id: 'Sai', text: 'Sai', isCorrect: false }
      ],
      answer: 'Đúng',
      points: 0.25,
      lesson: 'Bài 1: Sử dụng máy tính an toàn'
    };

    const html = generateExamWordHtml([tfQ], {
      donVi: 'PHÒNG GD&ĐT',
      tenTruong: 'THCS LÊ HỒNG PHONG',
      tenKyThi: 'KIỂM TRA GIỮA KÌ I',
      monHoc: 'MÔN: TIN HỌC – LỚP 7'
    });

    expect(html).toContain('Khi máy tính đang xử lí dữ liệu, việc ngắt nguồn điện đột ngột có thể gây lỗi tệp tin hệ thống.');
    // Should NOT contain option tags like A. Đúng or A. hoặc B.
    expect(html).not.toContain('<strong>A.</strong>');
    expect(html).not.toContain('<strong>B.</strong>');
    // Answer grid should have Đ
    expect(html).toContain('>Đ</td>');
  });

  it('generateExamVariants should generate answerKey with Đúng / Sai and 0.25 points', () => {
    const tfQ: ExerciseQuestion = {
      id: 'tf_single_1',
      category: 'mc',
      questionType: 'true-false',
      level: 'NB',
      content: 'Ổ đĩa thể rắn (SSD) có tốc độ truy xuất dữ liệu nhanh hơn ổ cứng HDD truyền thống.',
      options: [
        { id: 'Đúng', text: 'Đúng', isCorrect: true },
        { id: 'Sai', text: 'Sai', isCorrect: false }
      ],
      answer: 'Đúng',
      points: 0.25,
      lesson: 'Bài 2'
    };

    const variants = generateExamVariants([tfQ], ['101']);
    expect(variants.length).toBe(1);
    expect(variants[0].answerKey[0].answer).toBe('Đúng');
    expect(variants[0].answerKey[0].points).toBe(0.25);
    expect(variants[0].answerKey[0].type).toBe('true-false');
  });
});

describe('Dynamic Exam File Name Generation Tests', () => {
  it('detectGradeFromContext should detect correct grade from question or headerInfo', () => {
    const q8 = [{ grade: '8', lesson: 'Bài 1' }];
    expect(detectGradeFromContext(q8)).toBe('8');

    const q6 = [{ grade: '6', lesson: 'Bài 1' }];
    expect(detectGradeFromContext(q6)).toBe('6');

    expect(detectGradeFromContext([], { monHoc: 'MÔN: TIN HỌC – LỚP 9' })).toBe('9');
  });

  it('buildDefaultFileName should adapt to grade and not force THUONG if not provided', () => {
    const q8 = [{ grade: '8', lesson: 'Bài 1' }];
    const header8 = {
      tenKyThi: 'KIỂM TRA GIỮA KÌ I - NĂM HỌC 2026–2027',
      monHoc: 'MÔN: TIN HỌC – LỚP 8'
    };

    // When teacher name is not provided
    const fileNameWithoutTeacher = buildDefaultFileName(q8, header8, '');
    expect(fileNameWithoutTeacher).toBe('GK1 TIN 8-26-27');
    expect(fileNameWithoutTeacher).not.toContain('THUONG');

    // When teacher name is custom e.g. LAN
    const fileNameWithLan = buildDefaultFileName(q8, header8, 'LAN');
    expect(fileNameWithLan).toBe('GK1 TIN 8-26-27-LAN');

    // When teacher name is THUONG
    const fileNameWithThuong = buildDefaultFileName(q8, header8, 'THUONG');
    expect(fileNameWithThuong).toBe('GK1 TIN 8-26-27-THUONG');

    // For Grade 6 Cuối kì 1
    const q6 = [{ grade: '6' }];
    const headerCK1 = {
      tenKyThi: 'KIỂM TRA CUỐI KÌ I - NĂM HỌC 2026–2027',
      monHoc: 'MÔN: TIN HỌC – LỚP 6'
    };
    expect(buildDefaultFileName(q6, headerCK1, '')).toBe('CK1 TIN 6-26-27');
  });
});
